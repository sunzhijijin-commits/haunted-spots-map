// 地図統計を更新
function updateMapStats(spots) {
    const totalSpots = hauntedSpots.length;
    const visibleSpots = spots.length;
    const highDanger = spots.filter(s => s.danger === '高').length;
    const midDanger = spots.filter(s => s.danger === '中').length;
    const lowDanger = spots.filter(s => s.danger === '低').length;
    
    document.getElementById('totalSpots').textContent = totalSpots;
    document.getElementById('visibleSpots').textContent = visibleSpots;
    document.getElementById('highDanger').textContent = highDanger;
    document.getElementById('midDanger').textContent = midDanger;
    document.getElementById('lowDanger').textContent = lowDanger;
}

function showSpotInfo(spot) {
    currentSpot = spot;
    
    // プレースホルダーを非表示にして詳細を表示
    const placeholder = document.querySelector('.placeholder-text');
    const spotDetails = document.querySelector('.spot-details');
    
    placeholder.style.display = 'none';
    spotDetails.classList.remove('hidden');
    
    // 画像を設定
    const spotImage = document.getElementById('spotImage');
    spotImage.src = spot.image;
    spotImage.alt = spot.name;
    
    // 基本情報
    document.getElementById('spotName').textContent = spot.name;
    document.getElementById('spotLocation').textContent = spot.location;
    document.getElementById('spotType').textContent = spot.type;
    
    // セクション情報
    document.getElementById('spotOverview').textContent = spot.overview;
    document.getElementById('spotHistory').textContent = spot.history;
    document.getElementById('spotRumor').textContent = spot.rumor;
    document.getElementById('spotExperience').textContent = spot.experience;
    document.getElementById('spotAccess').textContent = spot.access;
    
    // 新しい情報フィールドの表示
    displayFolklore(spot.folklore);
    displayTestimonies(spot.testimonies);
    displayNews(spot.news);
    displayMedia(spot.media);
    
    // Amazonアフィリエイトリンクを表示（スポット情報を渡す）
    displayAffiliateLinks(spot);
    
    const dangerSpan = document.getElementById('spotDanger');
    dangerSpan.textContent = spot.danger;
    
    // 危険度によって色を変える
    switch(spot.danger) {
        case '高':
            dangerSpan.style.background = 'rgba(255, 0, 0, 0.3)';
            dangerSpan.style.color = '#ff6b6b';
            break;
        case '中':
            dangerSpan.style.background = 'rgba(255, 165, 0, 0.3)';
            dangerSpan.style.color = '#ffa500';
            break;
        case '低':
            dangerSpan.style.background = 'rgba(0, 255, 0, 0.3)';
            dangerSpan.style.color = '#51cf66';
            break;
    }
    
    // お気に入りボタンを更新
    updateFavButton();
    
    // ストリートビューセクションを非表示に
    document.getElementById('streetViewSection').style.display = 'none';
    document.getElementById('streetView').innerHTML = '';
    
    // マップを該当位置に移動
    map.setView([spot.lat, spot.lng], 12);
    
    // 右側パネルを一番上にスクロール
    document.getElementById('spotInfo').scrollTop = 0;
}

