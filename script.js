// モバイル機能のセットアップ
function setupMobileFeatures() {
    const mobileMenuToggle = document.getElementById('mobileMenuToggle');
    const mobileOverlay = document.getElementById('mobileOverlay');
    const controlsPanel = document.getElementById('controlsPanel');
    const fabTop = document.getElementById('fabTop');
    const fabMap = document.getElementById('fabMap');
    
    // ハンバーガーメニュートグル
    if (mobileMenuToggle) {
        mobileMenuToggle.addEventListener('click', () => {
            controlsPanel.classList.toggle('mobile-open');
            mobileOverlay.classList.toggle('active');
            mobileMenuToggle.textContent = controlsPanel.classList.contains('mobile-open') ? '✕' : '☰';
        });
    }
    
    // オーバーレイクリックでメニューを閉じる
    if (mobileOverlay) {
        mobileOverlay.addEventListener('click', () => {
            controlsPanel.classList.remove('mobile-open');
            mobileOverlay.classList.remove('active');
            mobileMenuToggle.textContent = '☰';
        });
    }
    
    // トップへ戻るボタン
    if (fabTop) {
        fabTop.addEventListener('click', () => {
            window.scrollTo({
                top: 0,
                behavior: 'smooth'
            });
        });
    }
    
    // 地図へスクロールボタン
    if (fabMap) {
        fabMap.addEventListener('click', () => {
            const mapElement = document.getElementById('map');
            if (mapElement) {
                mapElement.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    }
    
    // スワイプジェスチャー対応（スポット情報パネル）
    const spotInfo = document.getElementById('spotInfo');
    if (spotInfo) {
        let startX = 0;
        let startY = 0;
        
        spotInfo.addEventListener('touchstart', (e) => {
            startX = e.touches[0].clientX;
            startY = e.touches[0].clientY;
        }, { passive: true });
        
        spotInfo.addEventListener('touchend', (e) => {
            const endX = e.changedTouches[0].clientX;
            const endY = e.changedTouches[0].clientY;
            const diffX = endX - startX;
            const diffY = endY - startY;
            
            // 横スワイプが縦スワイプより大きい場合
            if (Math.abs(diffX) > Math.abs(diffY) && Math.abs(diffX) > 50) {
                if (diffX > 0) {
                    // 右スワイプ: 前のスポット
                    navigateSpot(-1);
                } else {
                    // 左スワイプ: 次のスポット
                    navigateSpot(1);
                }
            }
        }, { passive: true });
    }
    
    // プルトゥリフレッシュの無効化（誤動作防止） - コントロールパネル外のみ
    document.body.addEventListener('touchmove', (e) => {
        if (controlsPanel.classList.contains('mobile-open')) {
            // コントロールパネル内のスクロールは許可
            if (!controlsPanel.contains(e.target)) {
                e.preventDefault();
            }
        }
    }, { passive: false });
    
    // コントロールパネル内のスクロールを明示的に有効化
    if (controlsPanel) {
        controlsPanel.addEventListener('touchmove', (e) => {
            e.stopPropagation();
        }, { passive: true });
    }
    
    // 画面回転時の調整
    window.addEventListener('orientationchange', () => {
        setTimeout(() => {
            if (map) {
                map.invalidateSize();
            }
        }, 100);
    });
    
    // スクロール時にFABの表示/非表示
    let lastScrollTop = 0;
    window.addEventListener('scroll', () => {
        const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
        const fabContainer = document.querySelector('.fab-container');
        
        if (fabContainer) {
            if (scrollTop > 300) {
                fabContainer.style.opacity = '1';
                fabContainer.style.pointerEvents = 'auto';
            } else {
                fabContainer.style.opacity = '0';
                fabContainer.style.pointerEvents = 'none';
            }
        }
        
        lastScrollTop = scrollTop;
    }, { passive: true });
}

// スポット間のナビゲーション（スワイプ用）
function navigateSpot(direction) {
    if (!currentSpot) return;
    
    const currentIndex = hauntedSpots.findIndex(spot => spot.id === currentSpot.id);
    let newIndex = currentIndex + direction;
    
    // ループ処理
    if (newIndex < 0) {
        newIndex = hauntedSpots.length - 1;
    } else if (newIndex >= hauntedSpots.length) {
        newIndex = 0;
    }
    
    const nextSpot = hauntedSpots[newIndex];
    if (nextSpot) {
        showSpotInfo(nextSpot);
        map.setView([nextSpot.lat, nextSpot.lng], 13);
    }
}

// タッチデバイス検出
function isTouchDevice() {
    return 'ontouchstart' in window || navigator.maxTouchPoints > 0;
}

// ビューポートサイズ取得（モバイル対応）
function getViewportHeight() {
    return window.innerHeight || document.documentElement.clientHeight;
}

// デバイスのタイプを判定
function getDeviceType() {
    const width = window.innerWidth;
    if (width < 480) return 'mobile';
    if (width < 768) return 'tablet';
    if (width < 1024) return 'laptop';
    return 'desktop';
}

// 初期化時にデバイスタイプをbodyに追加
document.body.classList.add(`device-${getDeviceType()}`);

