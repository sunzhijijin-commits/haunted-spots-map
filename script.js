function initMap() {
    // 日本の中心座標
    map = L.map('map', {
        minZoom: 5,
        maxZoom: 18,
        maxBounds: [[24, 122], [46, 149]],
        maxBoundsViscosity: 1.0
    }).setView([36.5, 138.0], 6);

    // OpenStreetMapタイル
    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '© OpenStreetMap contributors',
        maxZoom: 18
    }).addTo(map);

    // マーカーを追加
    addMarkers(hauntedSpots);
    
    // 地図クリックイベント
    map.on('click', function(e) {
        showMapOverlay();
    });
    
    // オーバーレイを初期表示
    updateMapStats(hauntedSpots);
}

function addMarkers(spots) {
    // 既存のマーカーをクリア
    markers.forEach(marker => map.removeLayer(marker));
    markers = [];

    spots.forEach(spot => {
        // 危険度によって色を変える
        let color;
        switch(spot.danger) {
            case '高':
                color = '#ff0000';
                break;
            case '中':
                color = '#ffa500';
                break;
            case '低':
                color = '#00ff00';
                break;
            default:
                color = '#667eea';
        }

        // カスタムアイコン
        const icon = L.divIcon({
            className: 'custom-marker',
            html: `<div class="marker-pin" style="background: ${color};"></div>`,
            iconSize: [30, 42],
            iconAnchor: [15, 42]
        });

        const marker = L.marker([spot.lat, spot.lng], { 
            icon: icon,
            spotId: spot.id  // スポットIDを追加
        })
            .addTo(map)
            .on('click', () => showSpotInfo(spot));

        // ポップアップも追加
        marker.bindPopup(`
            <div style="color: #333;">
                <strong>${spot.name}</strong><br>
                ${spot.location}
            </div>
        `);

        markers.push(marker);
    });
    
    // 統計を更新
    updateMapStats(spots);
}

