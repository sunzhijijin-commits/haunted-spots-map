// コメントを取得する関数（Firebase使用）
async function getComments(spotId) {
    if (!window.firebaseDB) {
        console.warn('Firebase not initialized yet');
        return [];
    }
    
    try {
        const commentsRef = window.firebaseRef(window.firebaseDB, `comments/${spotId}`);
        const snapshot = await window.firebaseGet(commentsRef);
        const commentsData = snapshot.val() || {};
        
        // オブジェクトを配列に変換
        const commentsArray = Object.entries(commentsData).map(([key, value]) => ({
            ...value,
            id: value.id || key
        }));
        
        // 返信を親コメントに紐付け
        const parentComments = commentsArray.filter(c => !c.replyTo);
        const replies = commentsArray.filter(c => c.replyTo);
        
        console.log('全コメント:', commentsArray.length, '親:', parentComments.length, '返信:', replies.length);
        
        parentComments.forEach(parent => {
            parent.replies = replies.filter(r => {
                // 数値と文字列の両方で比較
                return r.replyTo == parent.id || String(r.replyTo) === String(parent.id);
            });
            if (parent.replies.length > 0) {
                console.log(`コメント ${parent.id} に ${parent.replies.length} 件の返信`);
            }
        });
        
        // 新しい順にソート
        return parentComments.sort((a, b) => b.timestamp - a.timestamp);
    } catch (error) {
        console.error('コメント取得に失敗しました:', error);
        return [];
    }
}

