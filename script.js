function filterSpots(type = currentFilter, region = currentRegion) {
    currentFilter = type;
    currentRegion = region;
    
    let filtered = hauntedSpots;
    
    // タイプフィルター
    if (type !== 'all') {
        filtered = filtered.filter(spot => spot.type === type);
    }
    
    // 地域フィルター
    if (region !== 'all') {
        const prefectures = regionMap[region];
        filtered = filtered.filter(spot => {
            return prefectures.some(pref => spot.location.includes(pref));
        });
    }
    
    addMarkers(filtered);
}

function getRegionFromLocation(location) {
    for (const [region, prefs] of Object.entries(regionMap)) {
        if (prefs.some(pref => location.includes(pref))) {
            return region;
        }
    }
    return '不明';
}

